"""Real Claude-backed Code Gen Agent (SDD §12 step 3).

Kept in its own module so the mock CLI path (backend/agents/codegen_agent.py) never
needs the anthropic/pydantic packages installed. Only imported when the CLI is run
with --engine claude.
"""

from __future__ import annotations

import anthropic
from pydantic import BaseModel

from backend.models.task import GeneratedFile, TaskStep

MODEL = "claude-opus-5"
MAX_CONTEXT_CHARS = 40_000

SYSTEM_PROMPT = """\
You are the Code Generation Agent of an automated software development pipeline
(SDD §3.2), implementing one step of a larger plan for a Python project. Given the
original feature request, the current step's description, and the contents of files
already generated by earlier steps, write the file(s) needed to implement this step.

Include pytest-style unit tests for any new function or module you add, in a
separate test file (SDD §7). Return complete, runnable file contents — no
placeholders, no partial diffs. Keep the project self-contained (no external
services, no database) unless the request clearly requires one. File paths are
relative to the project root."""


class FileSpec(BaseModel):
    path: str
    content: str


class CodeGenSpec(BaseModel):
    files: list[FileSpec]


class ClaudeCodeGenAgent:
    """Calls the real Claude API to implement one plan step as file contents."""

    def __init__(self, client: anthropic.Anthropic | None = None) -> None:
        self.client = client or anthropic.Anthropic()

    def generate(
        self,
        step: TaskStep,
        user_prompt: str,
        existing_files: list[GeneratedFile],
    ) -> list[GeneratedFile]:
        user_message = self._render_user_message(step, user_prompt, existing_files)
        try:
            response = self.client.messages.parse(
                model=MODEL,
                max_tokens=8000,
                system=SYSTEM_PROMPT,
                messages=[{"role": "user", "content": user_message}],
                output_format=CodeGenSpec,
            )
        except anthropic.AuthenticationError as exc:
            raise RuntimeError(
                "Claude API authentication failed during code generation — check "
                "ANTHROPIC_API_KEY."
            ) from exc
        except anthropic.RateLimitError as exc:
            raise RuntimeError(
                "Claude API rate limited during code generation."
            ) from exc
        except anthropic.APIConnectionError as exc:
            raise RuntimeError(
                "Could not reach the Claude API during code generation."
            ) from exc
        except anthropic.APIStatusError as exc:
            raise RuntimeError(
                f"Claude API error during code generation: {exc}"
            ) from exc

        spec = response.parsed_output
        return [GeneratedFile(path=f.path, content=f.content) for f in spec.files]

    def _render_user_message(
        self,
        step: TaskStep,
        user_prompt: str,
        existing_files: list[GeneratedFile],
    ) -> str:
        parts = [
            f"Original feature request: {user_prompt}",
            f"Current step: {step.description}",
        ]

        if existing_files:
            budget = MAX_CONTEXT_CHARS
            kept: list[GeneratedFile] = []
            for file in reversed(existing_files):
                if budget - len(file.content) < 0:
                    break
                kept.append(file)
                budget -= len(file.content)
            kept.reverse()

            parts.append("Files already generated by earlier steps:")
            for file in kept:
                parts.append(f"## {file.path}\n```\n{file.content}\n```")

        return "\n\n".join(parts)
